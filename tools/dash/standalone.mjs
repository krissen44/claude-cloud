// Builds a standalone, offline Scrappy Dash (one HTML file, no server) from public/index.html:
// the game's own CSS, demo dogs (DATA), sounds (S), the deterministic sim (//@dash) and the Dash UI + drawing.
// Usage: node tools/dash/standalone.mjs <out.html>
import fs from "node:fs";
const src = fs.readFileSync(new URL("../../public/index.html", import.meta.url), "utf8");
const cut = (from, to, keepEnd) => {
  const a = src.indexOf(from); if (a < 0) throw new Error("not found: " + from);
  const b = src.indexOf(to, a + from.length); if (b < 0) throw new Error("not found: " + to);
  return src.slice(a, keepEnd ? b + to.length : b);
};
const css = cut("<style>", "</style>", true);
const data = cut("const DATA = ", "\n");
const sound = cut("const S = (() => {", "\n})();", true);
const sim = cut("//@dash —", "//@/dash", true);
const signIn = "'<p class=\"mini2\">Sign in to put your runs on the daily ranking.</p>'";
const ui = cut("/* ============================ Scrappy Dash", "/* ============================ Bark Arena TV")
  .replace(signIn, "'<p class=\"mini2\">Offline version · rankings and prizes: game.scrappyxrp.fun</p>'");
if (!ui.includes("Offline version")) throw new Error("sign-in line not found");
const out = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Scrappy Dash</title>
<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Press+Start+2P&display=swap" rel="stylesheet">
${css}
<style>
body.home{background:#0e1726}
.solo .dashhero{margin-bottom:12px}
.skins{display:flex;gap:8px;justify-content:center;margin-top:12px;flex-wrap:wrap}
.skins button{font:inherit;font-size:11px;padding:6px 12px;border-radius:999px;border:2px solid rgba(255,255,255,.35);background:transparent;color:#fff;cursor:pointer}
.skins button.on{background:#ffd54f;border-color:#ffd54f;color:#0e1726}
.foot{text-align:center;font-size:11px;color:var(--ink2);margin-top:14px}
.foot a{color:var(--accent)}
</style>
</head>
<body class="home"><div class="wrap solo"><div id="app"></div></div>
<script>
/* Scrappy Dash — standalone build (generated by tools/dash/standalone.mjs from the Bark Arena page). Offline: no
   rankings, no wallet; best score and chosen dog/skin stay in this browser. */
${data}
const app = document.getElementById('app');
const esc = s => String(s).replace(/[&<>]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;'}[c]));
function lsGet(k){ try { return JSON.parse(localStorage.getItem(k)); } catch(e){ return null; } }
function lsSet(k, v){ try { localStorage.setItem(k, JSON.stringify(v)); } catch(e){} }
${sound}
// what the Dash code expects from the game around it — here: offline, demo dogs only
const CONFIG = {WORKER_URL: ''};
const WALLET = {demo: true, token: null};
const OWNED = null;
const LIVE = () => false;
const PRIZE = {list: [], done: false};
const prizeCards = () => '', loadPrizes = () => {}, chatSync = () => {}, api = () => Promise.reject(new Error('offline'));
const tokenOf = f => f && (f.token || +f.id) || null;
let tab = 'dash';
const ROSTER = () => DATA.fighters;
const bondOrder = R => R.slice();
const SAVE = (() => {
  let d = lsGet('dash_solo') || {};
  const today = () => new Date().toISOString().slice(0, 10);
  return {get data(){ return d; }, today, save(){ lsSet('dash_solo', d); }, bondXp(){ return []; }, dog(){ return {lvl: 1, xp: 0, w: 0, l: 0}; }};
})();
${sim}
${ui}
// ---- the standalone hangar (instead of the game's Dash tab) ----
let SOLO_SKIN = lsGet('dash_skin') || (Date.now() < DASH_ROCKET_FROM ? 'sleigh' : 'rocket');
dashTheme = () => DASH_SKIN[SOLO_SKIN] ? SOLO_SKIN : 'sleigh';
function menu(){
  const th = dashTheme(), K = DASH_SKIN[th], me = dashPickDog(), sv = dashSave();
  const pick = ROSTER().map(f => \`<button data-dashdog="\${esc(f.id)}" class="\${me && me.id === f.id ? 'insq' : ''}"><img src="\${f.img}" alt=""><span><b>\${esc(f.name)}</b><br>\${esc(f.rarity)}</span></button>\`).join('');
  app.innerHTML = \`<div class="card dashhero dash-\${th}">
      \${th === 'sleigh' ? '<i class="dashsnow" aria-hidden="true"></i><i class="dashmoon" aria-hidden="true"></i>' : ''}
      <div class="dashtitle">\${K.icon} SCRAPPY<br>\${K.title}</div>
      <p class="dashsub">Fly \${K.where}. <b>Hold</b> to climb · let go to sink · <b>quick tap</b> drops a \${K.ammo}.</p>
      <p class="dashsub">Hit the \${K.target} for a combo (up to ×5), grab \${K.ammos} and \${K.coins}, dodge \${K.obst} and \${K.foe} — skim past them for a close-call bonus. It gets faster every second.</p>
      <button id="dashGo" class="dashgo">▶ PLAY</button>
      <p class="dashsub" style="margin-top:10px">Best on this device: <b>\${sv.best.toLocaleString()}</b> · \${sv.runs} run\${sv.runs === 1 ? '' : 's'}</p>
      <div class="skins">\${Object.keys(DASH_SKIN).map(k => \`<button data-skin="\${k}" class="\${k === th ? 'on' : ''}">\${DASH_SKIN[k].icon} \${DASH_SKIN[k].title}</button>\`).join('')}</div>
    </div>
    <div class="card"><h3 class="h3">PILOT</h3><div class="pick tiny">\${pick}</div></div>
    <p class="foot">Scrappy Dash · a Bark Arena mini game · <a href="https://game.scrappyxrp.fun/" target="_blank" rel="noopener">game.scrappyxrp.fun</a></p>\`;
  app.querySelectorAll('[data-dashdog]').forEach(b => b.onclick = () => { S.click(); DASH.dog = b.dataset.dashdog; lsSet('ba_dashdog', DASH.dog); menu(); });
  app.querySelectorAll('[data-skin]').forEach(b => b.onclick = () => { S.click(); SOLO_SKIN = b.dataset.skin; lsSet('dash_skin', SOLO_SKIN); menu(); });
  document.getElementById('dashGo').onclick = () => { S.unlock(); S.click(); dashPlay(dashPickDog()); };
}
menu();
</script>
</body></html>
`;
fs.writeFileSync(process.argv[2] || "scrappy-dash.html", out);
console.log("wrote", process.argv[2] || "scrappy-dash.html", out.length, "bytes");
